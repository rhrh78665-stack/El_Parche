import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
const stores=new Map();
const storage=new Map();
globalThis.sessionStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
globalThis.window=new EventTarget();
globalThis.indexedDB={open(){const req={};queueMicrotask(()=>{const db={createObjectStore(n){stores.set(n,new Map())},transaction(n){const t={objectStore(){return {put(v){stores.get(n).set(v.id,structuredClone(v));queueMicrotask(()=>t.oncomplete?.())},delete(k){stores.get(n).delete(k);queueMicrotask(()=>t.oncomplete?.())},getAll(){const q={};queueMicrotask(()=>{q.result=[...stores.get(n).values()].map(x=>structuredClone(x));q.onsuccess?.()});return q}}}};return t}};req.result=db;req.onupgradeneeded?.();req.onsuccess?.()});return req}};
let online=true,forzarRechazo=false;
const aceptadas=new Map();
globalThis.fetch=async(path,options)=>{
 if(!online)throw new TypeError('Sin red');
 const datos=JSON.parse(options.body||'{}');
 let valor;
 if(path==='/api/catalogo')valor={usuario:{id:'caja',rol:'cajera'},acciones:{}};
 else if(path.endsWith('version_privacidad'))valor={version:0};
 else if(path.endsWith('menu_disponible'))valor=[{id:'h',nombre:'Producto',precio:15000}];
 else if(path.endsWith('cola_pedidos'))valor=[];
 else if(path.endsWith('registrar_pedido')){
  if(forzarRechazo)return {ok:false,status:400,json:async()=>({error:'Sin existencias'})};
  const id=options.headers['Idempotency-Key'];
  if(!aceptadas.has(id))aceptadas.set(id,{id:datos.id,total:15000});
  valor=aceptadas.get(id);
 }else valor={ok:true};
 return {ok:true,status:200,json:async()=>structuredClone(valor)};
};
const modulo=await import(pathToFileURL(resolve(process.argv[2]||'web/transporte.js')).href);
await modulo.transporte('/api/catalogo');
await modulo.transporte('/api/accion/menu_disponible',{},crypto.randomUUID());
await modulo.transporte('/api/accion/cola_pedidos',{},crypto.randomUUID());
online=false;
const id=crypto.randomUUID();
const datos={canal:'mostrador',lineas:[{producto:'h',cantidad:1}]};
let r=await modulo.transporte('/api/accion/registrar_pedido',structuredClone(datos),id);
assert.equal(r.pendiente,true);
await modulo.transporte('/api/accion/registrar_pedido',structuredClone(datos),id);
assert.equal((await modulo.pendientes()).length,1);
assert.equal((await modulo.transporte('/api/accion/cola_pedidos',{},crypto.randomUUID())).length,1);
assert.equal((await modulo.transporte('/api/accion/menu_disponible',{},crypto.randomUUID()))[0].id,'h');
online=true;
await modulo.sincronizar();
assert.equal((await modulo.pendientes()).length,0);
assert.equal(aceptadas.size,1);
forzarRechazo=true;
await assert.rejects(()=>modulo.transporte('/api/accion/registrar_pedido',structuredClone(datos),crypto.randomUUID()));
assert.equal((await modulo.pendientes())[0].estado,'rechazada');
await modulo.descartar((await modulo.pendientes())[0].id);
assert.equal((await modulo.pendientes()).length,0);
console.log('Transporte: caché, pedido pendiente, reintento sin duplicar, sincronización y rechazo correctos en almacenamiento simulado.');
process.exit(0);
